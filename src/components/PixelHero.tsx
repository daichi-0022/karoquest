// ─────────────────────────────────────────────────────────────
//  スプライト定義テーブル
// ─────────────────────────────────────────────────────────────
const SPRITES = [
  { minLv: 30, map: MAP30, pal: PAL30 },
  { minLv: 20, map: MAP20, pal: PAL20 },
  { minLv: 10, map: MAP10, pal: PAL10 },
  { minLv:  5, map: MAP5,  pal: PAL5  },
  { minLv:  1, map: MAP1,  pal: PAL1  },
];

function getSprite(level: number) {
  return SPRITES.find(s => level >= s.minLv) ?? SPRITES[SPRITES.length - 1];
}

// ─────────────────────────────────────────────────────────────
//  コンポーネント
// ─────────────────────────────────────────────────────────────
interface Props {
  level: number;
  size?: number;
  animate?: boolean;
}

export default function PixelHero({ level, size = 128, animate = true }: Props) {
  const floatAnim = useRef(new Animated.Value(0)).current;
  const { map, pal } = getSprite(level);
  const gridSize = map.length;          // 32
  const px = size / gridSize;           // 128/32 = 4px per pixel

  useEffect(() => {
    if (!animate) return;
    const loop = Animated.loop(
      Animated.sequence([
        Animated.timing(floatAnim, { toValue: -px, duration: 700, useNativeDriver: true }),
        Animated.timing(floatAnim, { toValue:   0, duration: 700, useNativeDriver: true }),
      ])
    );
    loop.start();
    return () => loop.stop();
  }, [animate, px]);

  return (
    <Animated.View style={{ transform: [{ translateY: floatAnim }] }}>
      <View style={{ width: size, height: size }}>
        {map.map((rowArr, ri) => (
          <View key={ri} style={{ flexDirection: 'row' }}>
            {rowArr.map((key, ci) => (
              <View
                key={ci}
                style={{
                  width: px,
                  height: px,
                  backgroundColor: key === '_' ? __ : (pal[key] ?? '#FF00FF'),
                }}
              />
            ))}
          </View>
        ))}
      </View>
    </Animated.View>
  );
}
